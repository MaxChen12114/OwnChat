// app/boot.ts — the boot orchestrator (the shell layer).
//
// This is where index.html's single boot line comes from: l0/build.mjs reads this file, substitutes
// the manifest for the placeholder and emits one line of script, so the file is a pure template — no
// imports, no DOM, no side effects. The only side effect, document.write, happens in the browser
// after emission.
//
// Order is the floor. The real load order of the classic scripts was only ever recorded in the order
// they were written, and l0/scripts.json is now the single source of truth; the loader writes tags
// out in manifest order. Parser-inserted tags behave like the original ones: same order, same
// DOMContentLoaded timing, same defer semantics for modules.
//
// The open tag must not contain a literal `</script` sequence (it is assembled as '</'+'script>'),
// or the inline body ends early — l0/manifest.mjs's inBody accounting and check-syntax both watch
// for that.
// @module app/boot

/**
 * One boot manifest entry, generated by l0/build.mjs from l0/scripts.json plus the on-disk content
 * hash. `s` is the src (a full URL for CDN entries), `v` the content hash (local files only), `t`
 * the script type (`module`), `x` the integrity attribute and `o` the crossorigin attribute.
 */
export interface BootEntry {
  s: string;
  v?: string;
  t?: string;
  x?: string;
  o?: string;
}

/**
 * The loader body: document.write one script tag per manifest entry.
 * l0/build.mjs inlines it into index.html's single boot line, as the code following `var m=<json>;`.
 * The text must stay byte-identical to what l0/build.mjs expects; test/l0-build.test.mjs locks it.
 */
export const BOOT_LOADER_BODY = "for(var i=0;i<m.length;i++){var e=m[i];document.write('<script'+(e.t?' type=\"'+e.t+'\"':'')+' src=\"'+e.s+(e.v?'?v='+e.v:'')+'\"'+(e.x?' integrity=\"'+e.x+'\"':'')+(e.o?' crossorigin=\"'+e.o+'\"':'')+'></'+'script>');}";

/** Assemble the complete one-line boot script from the manifest and the loader body (the emitter's only exit). */
export function renderBootLine(items: BootEntry[]): string {
  return "<script>/*l0-boot-v1*/(function(){var m=" + JSON.stringify(items) + ";" + BOOT_LOADER_BODY + "})();</script>";
}
